package arrays;

/*
 * Problem: Trapping Rain Water (LeetCode #42) - Hard
 * Link: https://leetcode.com/problems/trapping-rain-water/
 * Approach: Two pointers. Always move the pointer on the shorter side,
 *           tracking the max height seen so far on each side.
 * Time: O(n) | Space: O(1)
 */
public class TrappingRainWater {
    public static int trap(int[] height) {
        int left = 0, right = height.length - 1;
        int leftMax = 0, rightMax = 0, water = 0;

        while (left < right) {
            if (height[left] < height[right]) {
                // Left side is the limiting side
                if (height[left] >= leftMax) {
                    leftMax = height[left];
                } else {
                    water += leftMax - height[left];
                }
                left++;
            } else {
                // Right side is the limiting side
                if (height[right] >= rightMax) {
                    rightMax = height[right];
                } else {
                    water += rightMax - height[right];
                }
                right--;
            }
        }
        return water;
    }

    public static void main(String[] args) {
        System.out.println(trap(new int[]{0, 1, 0, 2, 1, 0, 1, 3, 2, 1, 2, 1})); // 6
    }
}